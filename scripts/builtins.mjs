// Writes api/_builtin-courses.js: ids of the starter courses, so the push server can tell a new course
// added from the admin screen from a change to a built-in one. Runs before every build.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../src/videos/catalog.ts', import.meta.url), 'utf8');
const ids = [...src.matchAll(/^\s*L\('[a-z]+',\s*'([^']+)'/gm)].map((m) => m[1]);
if (!ids.length) throw new Error('no built-in courses found in catalog.ts');
const out = `// Generated by scripts/builtins.mjs from src/videos/catalog.ts. Do not edit.\nexport const BUILTIN_COURSES = ${JSON.stringify(ids)};\n`;
writeFileSync(new URL('../api/_builtin-courses.js', import.meta.url), out);
